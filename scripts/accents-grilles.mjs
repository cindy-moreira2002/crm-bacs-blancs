//  REMETTRE LES ACCENTS DANS LES GRILLES DE NOTATION
//
//    node scripts/accents-grilles.mjs            (rapport seul, n'ecrit rien)
//    node scripts/accents-grilles.mjs --apply    (ecrit en base)
//    node scripts/accents-grilles.mjs --diff     (montre tous les textes changes)
//
//  POURQUOI. Le SQL d'installation des matieres est volontairement en ASCII
//  pur : l'editeur SQL de Supabase abime les accents colles depuis un Mac.
//  Les descriptions de paliers sont donc arrivees en base sans accents
