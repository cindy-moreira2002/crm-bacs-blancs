/** Rend a `accentue` la casse de `original` (Maitrise → Maîtrise). */
function memeCasse(original, accentue) {
  if (original === original.toUpperCase() && original.length > 1) return accentue.toUpperCase();
  if (original[0] === original[0].toUpperCase()) {
    return accentue[0].toUpperCase() + accentue.slice(1);
  }
  return accentue;
}

/**
 * Remet les accents dans un texte.
 *
 * Un texte qui en porte deja n'est pas touche : il a ete ecrit correctement,
 * et le dictionnaire n'a rien a y faire.
 */
export function accentuer(texte) {
  if (typeof texte !== 'string' || !texte) return texte;
  if (/[à-ÿÀ-Ÿ]/.test(texte)) return texte;
  let sortie = texte.replace(/[A-Za-z']+/g, (mot) => {
    const cible = ACCENTS[mot.toLowerCase()];
    return cible ? memeCasse(mot, cible) : mot;
  });
  // « a » isolé. Dans ces grilles c'est toujours la préposition « à » : le
  // corpus a été relu, il n'y contient ni « il a », ni « il y a », ni « n'a ».
  // La règle reste volontairement étroite — un « a » en début de phrase ou
  // suivi d'un participe passé n'est pas touché.
  sortie = sortie.replace(/(^|[^\S\n])a(?= )/g, (tout, avant, index) => {
    const suite = sortie.slice(index + tout.length + 1, index + tout.length + 30);
    // Seules formes du VERBE avoir qui pourraient apparaître un jour. « a la
    // question », « a une autre » sont bien la préposition : on les accentue.
    if (/^(été|pas |plus |jamais )/.test(suite)) return tout;
    return `${avant}à`;
  });
  for (const [avant, apres] of EXCEPTIONS) sortie = sortie.split(avant).join(apres);
  return sortie;
}

