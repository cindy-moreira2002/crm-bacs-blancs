//
//  COMMENT. Mot a mot, avec un dictionnaire EXPLICITE. Aucune heuristique :
//  un mot absent du dictionnaire n'est pas touche. Les mots ambigus en sont
//  volontairement absents — « a » (a / a), « ou » (ou / ou), « note »
//  (note / note) : un accent pose au hasard change le sens.
//
//  La casse et la ponctuation sont conservees : « Maitrise » redevient
//  « Maitrise » avec sa majuscule.
//
//  IDEMPOTENT : rejouable sans risque. Un texte deja accentue ne bouge plus.
//  Ecrit une sauvegarde horodatee avant toute modification.
// =====================================================================

